import type { Metadata } from 'next';
import { notFound } from 'next/navigation';
import Link from 'next/link';
import PendingHint from '@/app/_components/pending-hint';
import { getProduct, products } from '@/lib/data';

// Pre-render one static page per product at build time.
export function generateStaticParams() {
  return products.map((product) => ({ id: product.id }));
}

// Per-route dynamic metadata — resolved from the same async params.
export async function generateMetadata({
  params,
}: PageProps<'/products/[id]'>): Promise<Metadata> {
  const { id } = await params;
  const product = getProduct(id);
  return { title: product ? product.name : 'Product not found' };
}

// PageProps<'/products/[id]'> is a global helper generated by `next typegen`
// (also by dev/build): params is typed from the folder name, no manual types.
export default async function Product({ params }: PageProps<'/products/[id]'>) {
  const { id } = await params;
  const product = getProduct(id);

  // Calling notFound() renders the nearest not-found.tsx (404).
  if (!product) notFound();

  return (
    <main>
      <h1>{product.name}</h1>
      <p>${product.price}</p>
      <h2>Two ways to handle a slow route</h2>
      <ul>
        <li>
          <Link href={`/products/${id}/reviews/1`}>Read review #1</Link>: has a{' '}
          <code>loading.tsx</code>, so navigation is instant and a fallback
          shows while the review loads.
        </li>
        <li>
          <Link href={`/products/${id}/specs`} prefetch={false}>
            Specs
            <PendingHint />
          </Link>
          : no <code>loading.tsx</code>, so the page waits for the server and
          the link itself shows a <code>useLinkStatus</code> spinner.
        </li>
      </ul>
    </main>
  );
}
